package el_2;

public class print_primitive_data_types {
    public static void main(String[] args) {
        int a = 5;
        float b = 5.5f;
        double c = 19.7500;
        boolean has_permission = false;
        char ch = 'a';

        System.out.printf("Integer a: " + a + "\nFloat b: " + b + "\nDouble c: " + 
                        c + "\nBoolean: " + has_permission + "\nChar ch: " + ch + "\n");
    }
}
